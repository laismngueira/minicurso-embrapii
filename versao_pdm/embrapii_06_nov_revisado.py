def estado_sistema(a, limiar=None):
    """Estado de referência: modelo de ML + regras físicas."""
    limiar = LINHA.limiar if limiar is None else limiar
    if a["prob_falha"] >= limiar or any(r["status"] == "CRÍTICO" for r in a["regras"]):
        return "ALARME"
    if a["prob_falha"] >= limiar / 2 or any(r["status"] == "ATENÇÃO" for r in a["regras"]):
        return "ATENÇÃO"
    return "NORMAL"


