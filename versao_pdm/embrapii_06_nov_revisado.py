def _grafico_tendencia(titulo, series, unidade, faixa=None, linhas=(), pontos=(), nd=1):
    W, H, x0, x1, y0, y1 = 320, 165, 46, 312, 34, 138
    todos = [v for _, valores, _ in series for v in valores]
    if not todos:
        return ""
    vmin, vmax = faixa if faixa else (min(todos + [l[0] for l in linhas]), max(todos + [l[0] for l in linhas]))
    if vmax - vmin < 1e-9:
        vmax += 1
    margem = (vmax - vmin) * 0.08 if not faixa else 0
    vmin, vmax = vmin - margem, vmax + margem
    n = LINHA.janela

    def px(i, total):
        return x0 + (x1 - x0) * (i + (n - total)) / max(n - 1, 1)

    def py(v):
        return y1 - (y1 - y0) * (min(max(v, vmin), vmax) - vmin) / (vmax - vmin)

    partes = [f'<rect x="{x0}" y="{y0}" width="{x1 - x0}" height="{y1 - y0}" fill="#FFFFFF" stroke="#E3ECF6"/>']
    for k in range(3):
        v = vmin + (vmax - vmin) * k / 2
        partes.append(f'<line x1="{x0}" x2="{x1}" y1="{py(v):.1f}" y2="{py(v):.1f}" stroke="#EEF3F9"/>')
        partes.append(f'<text x="{x0 - 4}" y="{py(v) + 3:.1f}" font-size="10.5" fill="{CINZA_TXT}" text-anchor="end">{br(v, nd)}</text>')
    for valor, cor, rotulo in linhas:
        partes.append(f'<line x1="{x0}" x2="{x1}" y1="{py(valor):.1f}" y2="{py(valor):.1f}" stroke="{cor}" stroke-width="1.2" stroke-dasharray="5 3"/>')
        partes.append(f'<text x="{x1 - 2}" y="{py(valor) - 3:.1f}" font-size="10" fill="{cor}" text-anchor="end">{rotulo}</text>')
    legenda = []
    for nome, valores, cor in series:
        total = len(valores)
        pts = " ".join(f"{px(i, total):.1f},{py(v):.1f}" for i, v in enumerate(valores))
        partes.append(f'<polyline points="{pts}" fill="none" stroke="{cor}" stroke-width="1.8" stroke-linejoin="round"/>')
        partes.append(f'<circle cx="{px(total - 1, total):.1f}" cy="{py(valores[-1]):.1f}" r="3" fill="{cor}"/>')
        legenda.append((nome, cor, valores[-1]))
    for i, v, cor, forma in pontos:
        total = len(LINHA.historico)
        if forma == "tri":
            x, y = px(i, total), y1 - 2
            partes.append(f'<polygon points="{x - 4:.1f},{y:.1f} {x + 4:.1f},{y:.1f} {x:.1f},{y - 7:.1f}" fill="{cor}"/>')
        else:
            partes.append(f'<circle cx="{px(i, total):.1f}" cy="{py(v):.1f}" r="3.2" fill="{cor}" stroke="#fff" stroke-width="1"/>')
    leg = "".join(
        f'<tspan fill="{cor}" font-weight="700"> ● </tspan><tspan fill="{MARINHO}">{nome} {br(ult, nd)}</tspan>'
        for nome, cor, ult in legenda
    )
    return f"""
<div class="pdm-tend"><svg viewBox="0 0 {W} {H}" width="100%" xmlns="http://www.w3.org/2000/svg" font-family="Open Sans, sans-serif">
  <text x="8" y="18" font-size="12.5" font-weight="700" fill="{AZ}" font-family="Fira Sans, sans-serif">{titulo.upper()}</text>
  <text x="{W - 6}" y="18" font-size="11" text-anchor="end">{leg}<tspan fill="{CINZA_TXT}"> {unidade}</tspan></text>
  {''.join(partes)}
  <text x="{x1}" y="{H - 10}" font-size="10" fill="{CINZA_TXT}" text-anchor="end">últimos {n} ciclos →</text>
</svg></div>"""


