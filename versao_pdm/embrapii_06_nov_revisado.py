# ---- Limpeza de LaTeX ----
# Mesmo pedindo texto simples, alguns modelos (como o gpt-oss) escrevem fórmulas em
# LaTeX por hábito. Uma instrução no prompt reduz, mas não garante; por isso a
# resposta passa por uma limpeza antes de ser exibida (pós-processamento).
_SIMBOLOS_LATEX = {
    r"\times": "x", r"\cdot": "x", r"\approx": "≈", r"\neq": "≠", r"\leq": "≤", r"\geq": "≥",
    r"\le": "≤", r"\ge": "≥", r"\pi": "π", r"\Delta": "Δ", r"\omega": "ω", r"\rightarrow": "→",
    r"\to": "→", r"\Rightarrow": "⇒", r"\pm": "±", r"\%": "%", r"\degree": "°", r"\circ": "°",
}


def _grupo(x):
    x = x.strip()
    return f"({x})" if re.search(r"[\s+\-x×/]", x) else x


def limpar_latex(texto):
    """Converte fórmulas em LaTeX (que algumas LLMs usam mesmo quando pedimos texto simples)
    para texto simples legível no Colab e no Gradio."""
    t = texto
    # delimitadores de equação: \[ \], \( \), $$ $$, $ $
    t = re.sub(r"\\\[\s*(.*?)\s*\\\]", r"\n\n\1\n\n", t, flags=re.S)
    t = re.sub(r"(?<!\\)\[\s*([^\[\]\n]*\\[A-Za-z][^\[\]\n]*?)\s*\]", r"\n\n\1\n\n", t)  # [ \frac.. ] sem a barra
    t = re.sub(r"\\\(\s*(.*?)\s*\\\)", r"\1", t, flags=re.S)
    t = re.sub(r"\$\$\s*(.*?)\s*\$\$", r"\n\n\1\n\n", t, flags=re.S)
    t = re.sub(r"(?<!\w)\$(?!\s)([^$\n]+?)(?<!\s)\$(?!\w)", r"\1", t)
    # comandos com argumento: \text{..}, \mathrm{..}, \frac{a}{b}, \sqrt{x}
    for _ in range(4):  # repete para resolver comandos aninhados
        t = re.sub(r"\\(?:text|mathrm|textbf|mathbf|operatorname|mbox)\s*\{([^{}]*)\}", r"\1", t)
        t = re.sub(r"\\[dt]?frac\s*\{([^{}]*)\}\s*\{([^{}]*)\}", lambda m: f"{_grupo(m[1])} / {_grupo(m[2])}", t)
        t = re.sub(r"\\sqrt\s*\{([^{}]*)\}", r"√(\1)", t)
    for comando, simbolo in sorted(_SIMBOLOS_LATEX.items(), key=lambda x: -len(x[0])):
        t = re.sub(re.escape(comando) + r"(?![A-Za-z])", simbolo, t)
    t = re.sub(r"\\(?:left|right|displaystyle|quad|qquad)(?![A-Za-z])", "", t)
    t = re.sub(r"\\[,;:! ]", " ", t)          # espaçamentos do LaTeX
    t = re.sub(r"\^\{([^{}]*)\}", r"^\1", t)  # x^{2} -> x^2
    t = re.sub(r"_\{([^{}]*)\}", r"_\1", t)   # x_{ar} -> x_ar
    t = t.replace("{,}", ",").replace("{.}", ".")      # 310{,}2 -> 310,2
    t = re.sub(r"Δ (?=[A-Za-z])", "Δ", t)             # Δ T -> ΔT
    t = re.sub(r"\n[ \t]+(?=\n)", "\n", t)
    t = re.sub(r"\n\n[ \t]+", "\n\n", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    t = re.sub(r"(?<=\S)[ \t]{2,}", " ", t)
    return t.strip()


