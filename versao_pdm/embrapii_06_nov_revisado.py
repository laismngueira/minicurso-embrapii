"""#### Passo 2 — Verificação da qualidade dos dados

Antes de usar os dados em um modelo ou em um prompt, é preciso verificá-los.
Dados ruins geram modelos ruins, e uma LLM alimentada com dados errados vai
produzir diagnósticos errados com toda a confiança.

A verificação cobre cinco pontos:

1. **Completude**: valores ausentes e registros duplicados.
2. **Faixas físicas**: cada variável dentro de limites plausíveis.
3. **Consistência física**: a temperatura do processo deve ser maior que a do ar.
4. **Consistência dos rótulos**: ciclos com falha e sem modo, ou com modo e sem falha.
5. **Regras × rótulos**: como o AI4I é sintético, as regras de cada modo de
   falha são conhecidas. Recalculamos as regras a partir dos sensores e
   conferimos se batem com os rótulos do dataset.


"""

def verificar_dados(df):
    relatorio = []

    def registrar(item, resultado, ok, detalhe=""):
        relatorio.append({"verificação": item, "resultado": resultado,
                          "status": "✅ OK" if ok else "⚠️ ATENÇÃO", "detalhe": detalhe})

    # 1. completude
    ausentes = int(df.isna().sum().sum())
    registrar("Valores ausentes", ausentes, ausentes == 0)
    duplicados = int(df["udi"].duplicated().sum())
    registrar("Registros duplicados (UDI)", duplicados, duplicados == 0)

    # 2. faixas físicas plausíveis
    faixas = {
        "temp_ar": (290, 310), "temp_proc": (300, 320), "rotacao": (1000, 3000),
        "torque": (0, 100), "desgaste": (0, 260),
    }
    for col, (vmin, vmax) in faixas.items():
        fora = int(((df[col] < vmin) | (df[col] > vmax)).sum())
        registrar(f"Faixa de {col} [{vmin}, {vmax}]", fora, fora == 0,
                  f"mín {df[col].min():.1f} · máx {df[col].max():.1f}")

    # 3. consistência física
    invertidas = int((df["temp_proc"] <= df["temp_ar"]).sum())
    registrar("Temp. processo > temp. ar", invertidas, invertidas == 0,
              f"ΔT entre {df['delta_t'].min():.1f} e {df['delta_t'].max():.1f} K")

    # 4. consistência dos rótulos
    soma_modos = df[MODOS_FALHA].sum(axis=1)
    falha_sem_modo = int(((df["falha"] == 1) & (soma_modos == 0)).sum())
    modo_sem_falha = int(((df["falha"] == 0) & (soma_modos > 0)).sum())
    registrar("Falha sem modo indicado", falha_sem_modo, falha_sem_modo == 0, "rótulo de falha sem causa")
    registrar("Modo indicado sem falha", modo_sem_falha, modo_sem_falha == 0, "modo marcado com falha = 0")

    # 5. regras físicas recalculadas × rótulos do dataset
    limite = df["tipo"].map(LIMITE_OSF)
    regras = {
        "HDF": (df["delta_t"] < 8.6) & (df["rotacao"] < 1380),
        "PWF": (df["potencia"] < 3500) | (df["potencia"] > 9000),
        "OSF": df["desgaste_torque"] > limite,
    }
    for modo, mascara in regras.items():
        rotulo = df[modo] == 1
        concordam = int((mascara & rotulo).sum())
        divergem = int((mascara ^ rotulo).sum())
        registrar(f"Regra {modo} × rótulo {modo}", f"{concordam} concordam · {divergem} divergem",
                  divergem == 0, f"regra: {int(mascara.sum())} · rótulo: {int(rotulo.sum())}")

    return pd.DataFrame(relatorio)


