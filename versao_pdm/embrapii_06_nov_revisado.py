        ax1.set_ylim(-0.02, 1.05); ax1.set_ylabel("Probabilidade"); ax1.legend(loc="upper left", fontsize=8)
        ax1.set_title(f"Monitoramento · ciclos {x[0]}–{x[-1]} · VP={vp} FP={fp} FN={fn}")
