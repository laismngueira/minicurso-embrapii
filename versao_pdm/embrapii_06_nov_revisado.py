def formatar_resposta_chat(texto, a, checks, tecnica, fontes=None):
    """Transforma a resposta da LLM (texto livre e/ou JSON) em um diagnóstico detalhado para o chat."""
    r = extrair_resposta(texto)
    j = r.get("json") or {}
    estado_llm = r.get("estado") or "não informado"
    modo_llm = r.get("modo") or "não informado"
    criticos = [x["modo"] for x in a["regras"] if x["status"] == "CRÍTICO"]
    modo_sis = " / ".join(criticos) or "NENHUM"
    nome_modo = NOMES_MODOS.get(modo_llm, "")

    md = [f"### {EMOJI_ESTADO.get(estado_llm, '⚪')} Diagnóstico do ciclo {a['ciclo']} · produto {a['tipo']} ({a['produto']})",
          f"**Técnica de prompt:** {tecnica}",
          "",
          "| | Resposta da LLM | Sistema (modelo + regras) |",
          "|---|---|---|",
          f"| **Estado** | {EMOJI_ESTADO.get(estado_llm, '')} {estado_llm} | {EMOJI_ESTADO[estado_sistema(a)]} {estado_sistema(a)} |",
          f"| **Modo provável** | {modo_llm}{' · ' + nome_modo if nome_modo and modo_llm != 'NENHUM' else ''} | {modo_sis} |"]

    calc = r.get("calculos") or {}
    referencias = [("delta_t_K", "ΔT (K)", a["delta_t"], 1), ("potencia_W", "Potência (W)", a["potencia"], 0),
                   ("desgaste_torque", "Desgaste × torque (min·N·m)", a["desgaste_torque"], 0)]
    for chave, nome, ref, nd in referencias:
        valor = calc.get(chave)
        try:
            valor = br(float(valor), nd)
        except (TypeError, ValueError):
            valor = "—" if valor is None else valor
        md.append(f"| {nome} | {valor} | {br(ref, nd)} |")
    md.append(f"| Probabilidade de falha (modelo) | — | {br(a['prob_falha'] * 100, 1)} % |")

    if j.get("justificativa"):
        md += ["", f"**Justificativa:** {j['justificativa']}"]
    if j.get("acao_recomendada"):
        md += ["", f"**Ação recomendada:** {j['acao_recomendada']}"]

    livre = r.get("texto_livre", "").strip()
    if livre:
        rotulo = "Raciocínio da LLM" if tecnica == "Chain-of-thought" else "Resposta da LLM"
        md += ["", f"**{rotulo}:**", "", livre]

    if fontes:
        md += ["", "**Documentação consultada (RAG):** " + "; ".join(fontes)]

    acertos = sum(c["ok"] for c in checks)
    divergentes = ", ".join(c["item"] for c in checks if not c["ok"])
    md += ["", "---",
           f"**Verificação automática:** {acertos}/{len(checks)} itens conferem "
           + ("✅" if acertos == len(checks) else f"⚠️ divergências em: {divergentes}")]
    return "\n".join(md)


def responder(pergunta, historico, tecnica, temperatura, incluir_modelo, usar_rag=True):
    historico = list(historico or [])
    if not pergunta or not pergunta.strip():
        pergunta = "Qual o estado da máquina neste ciclo e qual ação você recomenda?"

    status = {k: "idle" for k, _ in ETAPAS}
    status["dados"] = "ativo"
    a = dict(LINHA.amostra_atual())  # retrato do ciclo atual da linha ao vivo
    historico = historico + [{"role": "user", "content": f"[{tecnica} · ciclo {a['ciclo']}] {pergunta}"}]
    yield historico, renderizar_pipeline(status), gr.update(), gr.update(), gr.update(), ""

    mensagens = TECNICAS[tecnica](pergunta, a, incluir_modelo)
    trechos = []
    status["dados"] = "concluido"
    if usar_rag:
        status["rag"] = "ativo"
        yield historico, renderizar_pipeline(status), gr.update(), gr.update(), gr.update(), ""
        mensagens, trechos = adicionar_contexto_rag(mensagens, pergunta, a)
        status["rag"] = "concluido"
    status["prompt"] = "ativo"
    texto_prompt = prompt_como_texto(mensagens)
    yield historico, renderizar_pipeline(status), renderizar_prompt(texto_prompt, tecnica, len(texto_prompt) // 4), \
        gr.update(), gr.update(), ""

    status.update(prompt="concluido", llm="ativo")
    yield historico, renderizar_pipeline(status), gr.update(), gr.update(), gr.update(), ""
    try:
        try:
            modelo = llm.model_copy(update={"temperature": float(temperatura)})
        except Exception:
            modelo = llm
        resposta = modelo.invoke(mensagens).content
    except Exception as e:
        resposta = f"Erro ao consultar a LLM: {e}"

    status.update(llm="concluido", verificacao="ativo")
    yield historico, renderizar_pipeline(status), gr.update(), gr.update(), gr.update(), ""

    checks = verificar_resposta(resposta, a)
    historico = historico + [{"role": "assistant", "content": formatar_resposta_chat(resposta, a, checks, tecnica, listar_fontes(trechos))}]
    diag = diagnosticar_amostra({k: a[k] for k in ["tipo", "temp_ar", "temp_proc", "rotacao", "torque", "desgaste"]},
                                plot=True)
    status["verificacao"] = "concluido"
    yield historico, renderizar_pipeline(status), gr.update(), renderizar_verificacao(checks, a), \
        base64_para_imagem(diag["grafico"]), ""


def base64_para_imagem(grafico_b64):
    if not grafico_b64:
        return None
    return Image.open(io.BytesIO(base64.b64decode(grafico_b64)))


