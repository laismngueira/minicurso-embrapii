"""#### Passo 6 — Otimização automática do limiar de alarme

O limiar de alarme funciona como o "ganho" do sistema de manutenção:

- limiar baixo: detecta mais falhas, mas gera mais falsos alarmes;
- limiar alto: menos falsos alarmes, mas falhas passam sem aviso.

A função buscar_melhor_limiar testa vários limiares sobre o conjunto de
**validação** e escolhe o de menor custo operacional:

    custo = custo_fn × (falhas não detectadas) + custo_fp × (falsos alarmes)

Por padrão, uma falha não detectada custa 10 vezes mais que um falso alarme
(parada não planejada contra uma inspeção desnecessária). A busca usa os
mesmos critérios de convergência do minicurso: para quando passa muitas
gerações sem melhora ou com o melhor custo repetido.

custo_fn / custo_fp: custo relativo de uma falha não detectada e de um
    falso alarme.

    geracoes_sem_melhora_max: gerações consecutivas sem melhora significativa
    antes de considerar convergido.

    geracoes_valor_repetido_max: gerações consecutivas com o melhor custo
    exatamente igual (estabilização total).

    tolerancia: variação mínima de custo para contar como melhora real.

    custo_alvo: se definido, encerra assim que o melhor custo atingir esse valor.

    seed: embaralha a ordem dos candidatos para os critérios de convergência
    não serem enviesados pela ordem da grade.
"""

import random
import time

prob_validacao = modelo_falha.predict_proba(validacao[FEATURES])[:, 1]
real_validacao = validacao["falha"].values


def custo_limiar(limiar, custo_fn, custo_fp):
    alarme = (prob_validacao >= limiar).astype(int)
    vp, fp, fn, precisao, recall, f1 = metricas_alarme(real_validacao, alarme)
    return custo_fn * fn + custo_fp * fp, vp, fp, fn, precisao, recall


def buscar_melhor_limiar(
    custo_fn=10.0,
    custo_fp=1.0,
    geracoes_sem_melhora_max=15,
    geracoes_valor_repetido_max=12,
    tolerancia=0.5,
    custo_alvo=None,
    seed=42,
    aplicar_na_linha=True,
):

    candidatos = [round(float(v), 3) for v in np.linspace(0.05, 0.95, 37)]
    random.Random(seed).shuffle(candidatos)

    total = len(candidatos)
    melhor, melhor_custo = None, 1e9
    geracoes_sem_melhora = 0
    geracoes_valor_repetido = 0
    custo_anterior = None
    avaliados = []
    inicio = time.time()

    print(
        f"🧠 Otimização iniciada. Até {total} limiares, custo FN={custo_fn} e FP={custo_fp}, "
        f"com convergência em {geracoes_sem_melhora_max} gerações sem melhora ou "
        f"{geracoes_valor_repetido_max} gerações com valor repetido.",
        flush=True,
    )

    for i, limiar in enumerate(candidatos, start=1):
        custo, vp, fp, fn, precisao, recall = custo_limiar(limiar, custo_fn, custo_fp)
        avaliados.append((limiar, custo))
        print(
            f"  [{i:02d}/{total}] limiar={limiar:.3f} -> custo={custo:.1f} "
            f"(VP={vp} FP={fp} FN={fn}; sem melhora há {geracoes_sem_melhora}, "
            f"valor repetido há {geracoes_valor_repetido})",
            flush=True,
        )

        if custo < melhor_custo - tolerancia:
            melhor_custo = custo
            melhor = {"limiar": limiar, "custo": custo, "vp": vp, "fp": fp, "fn": fn,
                      "precisao_val": precisao, "recall_val": recall}
            geracoes_sem_melhora = 0
            print(f"    Novo melhor custo: {custo:.1f}.", flush=True)
        else:
            geracoes_sem_melhora += 1

        if custo_anterior is not None and round(melhor_custo, 6) == round(custo_anterior, 6):
            geracoes_valor_repetido += 1
        else:
            geracoes_valor_repetido = 0
        custo_anterior = melhor_custo

        if custo_alvo is not None and melhor_custo <= custo_alvo:
            print(f"🎯 Meta de custo atingida. Parando em {i}/{total}.", flush=True)
            break
        if geracoes_sem_melhora >= geracoes_sem_melhora_max:
            print(f"🛑 Convergência por estagnação. Parando em {i}/{total}.", flush=True)
            break
        if geracoes_valor_repetido >= geracoes_valor_repetido_max:
            print(f"🛑 Convergência por valor repetido. Parando em {i}/{total}.", flush=True)
            break

    print(
        f"🧠 Otimização concluída em {time.time() - inicio:.2f}s. Melhor limiar: "
        f"{melhor['limiar']:.3f} (custo={melhor['custo']:.1f}).",
        flush=True,
    )

    if aplicar_na_linha:
        LINHA.limiar = melhor["limiar"]

    # ---- gráfico: custo × limiar + curva precisão-recall na validação ----
    avaliados.sort()
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4))
    ax1.plot([a[0] for a in avaliados], [a[1] for a in avaliados], "o-", color=AZUL, ms=4)
    ax1.axvline(melhor["limiar"], color=VERMELHO, ls="--", label=f"Melhor = {melhor['limiar']:.3f}")
    ax1.set_xlabel("Limiar de alarme"); ax1.set_ylabel("Custo (validação)")
    ax1.set_title(f"Custo = {custo_fn}·FN + {custo_fp}·FP"); ax1.legend()
    pr, rc, lim = precision_recall_curve(real_validacao, prob_validacao)
    ax2.plot(rc, pr, color=AZUL, lw=2)
    ax2.scatter([melhor["recall_val"] / 100], [melhor["precisao_val"] / 100], color=VERMELHO, s=60, zorder=5,
                label="Ponto escolhido")
    ax2.set_xlabel("Recall"); ax2.set_ylabel("Precisão"); ax2.set_title("Precisão × recall (validação)")
    ax2.legend()
    plt.tight_layout(); plt.show()
    grafico = figura_para_base64(fig)

    # desempenho do limiar escolhido na linha ao vivo (dados futuros)
    teste = monitorar_linha(inicio=0, n_amostras=len(linha_ao_vivo), limiar=melhor["limiar"], plot=False)
