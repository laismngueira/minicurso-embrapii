def extrair_resposta(texto):
    saida = {}
    blocos_json = re.findall(r"\{(?:[^{}]|\{[^{}]*\})*\}", texto or "")
    saida["json"], saida["texto_livre"] = {}, (texto or "").strip()
    for bloco in reversed(blocos_json):
        try:
            j = json.loads(bloco)
            saida["estado"] = str(j.get("estado", "")).upper() or None
            saida["modo"] = str(j.get("modo_provavel", "")).upper() or None
            saida["calculos"] = j.get("calculos") or {}
            saida["json"] = j
            livre = (texto or "").replace(bloco, "")
            saida["texto_livre"] = re.sub(r"```(json)?\s*```", "", livre).strip()
            break
        except Exception:
            continue
    if not saida.get("estado"):
        m = re.findall(r"estado\W{0,4}\s*[:=]\s*\**\s*(NORMAL|ATEN[ÇC][ÃA]O|ALARME)", texto or "", re.I)
        saida["estado"] = m[-1].upper().replace("ATENCAO", "ATENÇÃO") if m else None
    if not saida.get("modo"):
        m = re.findall(r"modo[^:\n]{0,20}[:=]\s*\**\s*(HDF|PWF|OSF|TWF|RNF|NENHUM)", texto or "", re.I)
        saida["modo"] = m[-1].upper() if m else None
    return saida


def verificar_resposta(texto, a):
    r = extrair_resposta(texto)
    criticos = [x["modo"] for x in a["regras"] if x["status"] == "CRÍTICO"]
    modo_regras = criticos[0] if criticos else "NENHUM"
    modo_real = a["modo_real"] if a["falha_real"] else "NENHUM"
    checks = []

    def add(item, valor_llm, referencia, ok):
        checks.append({"item": item, "llm": valor_llm if valor_llm is not None else "—",
                       "referencia": referencia, "ok": ok})

    add("Estado", r.get("estado"), estado_sistema(a), r.get("estado") == estado_sistema(a))
    add("Modo × regras físicas", r.get("modo"), " / ".join(criticos) or "NENHUM",
        r.get("modo") in (criticos or ["NENHUM"]))
    add("Modo × rótulo real (AI4I)", r.get("modo"), modo_real,
        r.get("modo") == modo_real or (modo_real == "NENHUM" and r.get("modo") in (None, "NENHUM")))

    calc = r.get("calculos") or {}
    referencias = {"delta_t_K": ("ΔT (K)", a["delta_t"]), "potencia_W": ("Potência (W)", a["potencia"]),
                   "desgaste_torque": ("Desgaste × torque", a["desgaste_torque"])}
    for chave, (nome, ref) in referencias.items():
        if chave in calc:
            try:
                v = float(calc[chave])
                add(f"Cálculo {nome}", round(v, 1), round(ref, 1), abs(v - ref) <= max(0.02 * abs(ref), 0.15))
            except (TypeError, ValueError):
                add(f"Cálculo {nome}", calc[chave], round(ref, 1), False)
    return checks


def perguntar_llm(pergunta, tecnica="Estruturado (PROMPT)", amostra=None, temperatura=0.1, incluir_modelo=True):
    a = amostra or LINHA.amostra_atual()
    mensagens = TECNICAS[tecnica](pergunta, a, incluir_modelo)
    try:
        modelo = llm.model_copy(update={"temperature": float(temperatura)})
    except Exception:
        modelo = llm
    resposta = modelo.invoke(mensagens).content
    return {
        "tecnica": tecnica, "prompt": prompt_como_texto(mensagens), "resposta": resposta,
        "verificacao": verificar_resposta(resposta, a), "amostra": a,
        "tokens_aprox": len(prompt_como_texto(mensagens)) // 4,
    }


